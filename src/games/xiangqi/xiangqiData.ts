import { Board, PType, Side } from './xiangqiRules'

export interface Endgame {
  id: string
  name: string
  rows: string[]
}

const CHAR2TYPE: Record<string, PType> = {
  K: 'K',
  A: 'A',
  B: 'B',
  N: 'N',
  R: 'R',
  C: 'C',
  P: 'P',
}

// 行 0 为红方底线，行 9 为黑方底线；'.' 为空；大写=红，小写=黑
export function parseEndgame(rows: string[]): Board {
  const board: Board = Array.from({ length: 10 }, () => Array(9).fill(null))
  for (let y = 0; y < 10; y++) {
    const row = rows[y]
    for (let x = 0; x < 9; x++) {
      const ch = row[x]
      if (ch === '.' || ch === ' ') continue
      const upper = ch.toUpperCase()
      const type = CHAR2TYPE[upper]
      const side: Side = ch === upper ? 'r' : 'b'
      board[y][x] = { side, type }
    }
  }
  return board
}

